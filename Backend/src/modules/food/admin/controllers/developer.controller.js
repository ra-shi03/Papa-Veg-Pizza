// Super admin > Developer: Env Managements, Image Setting, Developer Settings (operational data).

const adminName = (req) => req.user?.name || req.user?.email || 'Super Admin';
const wrap = (message, fn) => async (req, res, next) => {
  try {
    return sendResponse(res, 200, message, await fn(req));
  } catch (error) {
    next(error);
  }
};

// ---- Env Managements ----------------------------------------------------------------------------
export const getEnv = wrap('Environment settings fetched', () => getEnvSettings());
export const updateEnv = wrap('Environment settings saved', (req) => updateEnvSettings(req.body || {}, adminName(req)));

// ---- Image Setting ------------------------------------------------------------------------------
const uploadStatus = async () => ({
  imageUploadProvider: await getImageProvider(),
  cloudinaryConfigured: isCloudinaryConfigured(),
  localAvailable: canStoreLocally(),
  publicApiUrl: config.publicApiUrl || '',
  nodeEnv: config.nodeEnv,
  localUploadDir: localUploadRoot(),
});

export const getUploadSettings = wrap('Upload settings fetched', () => uploadStatus());
export const updateUploadSettings = wrap('Upload settings saved', async (req) => {
  const provider = req.body?.imageUploadProvider;
  if (!['local', 'cloudinary'].includes(provider)) throw new ValidationError('imageUploadProvider must be "local" or "cloudinary"');
  if (provider === 'cloudinary' && !isCloudinaryConfigured()) {
    throw new ValidationError('Cloudinary is not configured on the server (missing CLOUDINARY_* values in the .env)');
  }
  if (provider === 'local' && !canStoreLocally()) {
    throw new ValidationError('Set the Public API URL first (Developer > Env Managements): the apps need it to load locally stored images');
  }
  await setImageProvider(provider, adminName(req));
  return uploadStatus();
});

