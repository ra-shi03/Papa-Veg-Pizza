const CONFIRM_PHRASE = 'DELETE OPERATIONAL DATA';

const groups = () => OPERATIONAL.map((g) => ({ ...g, Model: mongoose.models[g.model] })).filter((g) => g.Model);

// GET /food/admin/operational-data: how many records each group holds
export const operationalCounts = wrap('Operational data counted', async () => {
  const list = groups();
  const counts = await Promise.all(list.map(({ Model }) => Model.countDocuments()));
  return {
    groups: list.map((g, i) => ({ key: g.key, label: g.label, count: counts[i] })),
    total: counts.reduce((sum, n) => sum + n, 0),
    confirmPhrase: CONFIRM_PHRASE,
  };
});

// POST /food/admin/operational-data/clear  { confirm: 'DELETE OPERATIONAL DATA' }
export const clearOperationalData = async (req, res, next) => {
  try {
    if (req.body?.confirm !== CONFIRM_PHRASE) {
      return res.status(400).json({ success: false, message: `Type "${CONFIRM_PHRASE}" to confirm` });
    }
    const deleted = {};
    for (const { key, Model } of groups()) {
      const result = await Model.deleteMany({});
      deleted[key] = result.deletedCount || 0;
    }
    return sendResponse(res, 200, 'Operational data cleared', {
      deleted,
      total: Object.values(deleted).reduce((sum, n) => sum + n, 0),
    });
  } catch (error) {
    next(error);
  }
};
